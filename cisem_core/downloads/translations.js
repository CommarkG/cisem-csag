export function tValue(val, lang) {
  if (!val) return val;
  if (lang !== 'he') return val;
  
  const trimmed = val.trim();
  if (translationMap[trimmed]) {
    return translationMap[trimmed];
  }
  
  // If it's a dynamic user label like "Yariv (BOSS)" or "Operator (PM)"
  const profileMatch = trimmed.match(/^([A-Za-z0-9\s]+)\s*\(([A-Za-z0-9\s]+)\)$/i);
  if (profileMatch) {
    const name = profileMatch[1].trim();
    const role = profileMatch[2].trim().toLowerCase();
    const transName = translationMap[name] || name;
    const transRole = translationMap[role] || role.toUpperCase();
    return `${transName} (${transRole})`;
  }
  
  return val;
}

